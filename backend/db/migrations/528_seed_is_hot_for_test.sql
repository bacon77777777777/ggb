-- 528: 標幾檔商品為「熱門」給老闆測試（前台那顆紅膠囊）
--
-- is_hot 從 527 起純粹是後台手動的精選標籤，不再參與任何排序。
-- 但全站 0 件標記，那顆膠囊從上線到現在沒出現過，沒東西可看。
--
-- 每個類別各挑一檔：轉蛋／盒玩挑實際抽最多的，其餘挑辨識度高的。
-- 這是測試資料，老闆之後在後台自己改。

UPDATE products SET is_hot = true WHERE name IN (
  '蠟筆小新姓名公仔吊飾',            -- 轉蛋：近期抽數第 3（31 分）
  'CAPSURIUM 吉伊卡哇場景',          -- 轉蛋：近期抽數第 2（76 分）
  '《間諜家家酒》安妮亞驚喜黏土人',  -- 盒玩：近期抽數第 1（85 分）
  '《我的英雄學院》-成為最棒英雄之前的故事-',  -- 一番賞
  '4周年 流星ガチャ',                -- 抽卡
  '七龍珠GT'                          -- 自製賞
);

SELECT type, name, is_hot FROM products WHERE is_hot ORDER BY type, name;
