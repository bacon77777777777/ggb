-- 619: 回收費率改成後台可調的一張表（老闆 2026-08-25「回收機制大改版」）
--
-- 變更重點：
--   ① 費率從函數裡的 hardcode 搬進 recycle_rates 表，後台「回收價格設定」頁可調
--   ② 基準一律是「單抽價」。不逐品項填實物價值 —— 沒人力，而且 product_prizes.recycle_value
--      這個欄位早就存在卻是 1,778 個品項零填寫，靠人工維護的方案不會被執行
--   ③ 品項層級的「回收設定」(decompose_type/decompose_value) 停用。全站 1,778 個品項
--      本來就全是 auto，沒有一個設過；留著只會讓兩套規則打架
--   ④ 結構依老闆指定：轉蛋、盒玩各一個 %；一番賞／抽卡／自製賞各有「大賞 %」與「小賞 %」
--
-- 大賞判定維持 total <= 3（品項初始總數）。一番賞的 A／B／C 賞平均 2.0–2.5 件，
-- 這個門檻抓得剛好；改用「總量佔比 < 5%」會讓 93% 的序列庫存變大賞（抽卡的 D 賞太多，
-- 害其他品項全部看起來很稀有），已試算否決。

CREATE TABLE IF NOT EXISTS public.recycle_rates (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_type  text        NOT NULL,
  -- all＝該類型不分賞等（轉蛋／盒玩）｜major＝大賞（total <= 3）｜normal＝一般賞
  tier          text        NOT NULL,
  rate_percent  numeric(6,2) NOT NULL,
  -- 下限。低價商品乘完不足 1 時至少給這個數，避免算出 0
  min_value     integer     NOT NULL DEFAULT 1,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  updated_by    text,
  CONSTRAINT recycle_rates_type_check CHECK (product_type IN ('gacha','blindbox','ichiban','card','custom')),
  CONSTRAINT recycle_rates_tier_check CHECK (tier IN ('all','major','normal')),
  CONSTRAINT recycle_rates_pct_check  CHECK (rate_percent >= 0 AND rate_percent <= 100),
  CONSTRAINT recycle_rates_min_check  CHECK (min_value >= 0),
  UNIQUE (product_type, tier)
);

COMMENT ON TABLE  public.recycle_rates IS '回收費率。基準為商品單抽價，後台「商品管理 → 回收價格設定」可調。';
COMMENT ON COLUMN public.recycle_rates.tier IS 'all＝不分賞等（轉蛋/盒玩）｜major＝大賞（品項初始總數 <= 3）｜normal＝一般賞';

