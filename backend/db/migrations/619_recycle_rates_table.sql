-- ── 費率查詢：大賞判定也只有這一份 ─────────────────────────
CREATE OR REPLACE FUNCTION public.recycle_rate_for(
  p_product_type text,
  p_prize_total  integer
) RETURNS TABLE (tier text, rate_percent numeric, min_value integer)
LANGUAGE sql STABLE AS $$
  SELECT r.tier, r.rate_percent, r.min_value
  FROM public.recycle_rates r
  WHERE r.product_type = p_product_type
    AND r.tier = CASE
          WHEN p_product_type IN ('gacha','blindbox') THEN 'all'
          -- total 為 NULL 時視為一般賞（與改版前的 IF total <= 3 行為一致）
          WHEN COALESCE(p_prize_total, 999) <= 3      THEN 'major'
          ELSE 'normal'
        END
  LIMIT 1;
$$;

-- ── calc_recycle_value 改讀費率表 ──────────────────────────
-- 舊簽名吃 decompose_type/decompose_value，改版後不再有品項層級設定，
-- 兩個呼叫端（dismantle_prizes、estimate_recycle_value）在本檔一併換掉。
DROP FUNCTION IF EXISTS public.calc_recycle_value(text, numeric, integer, text, integer);

CREATE OR REPLACE FUNCTION public.calc_recycle_value(
  p_product_type text,
  p_price        numeric,
  p_prize_total  integer
) RETURNS integer
LANGUAGE sql STABLE AS $$
  SELECT GREATEST(
           r.min_value,
           FLOOR(COALESCE(p_price, 0) * r.rate_percent / 100)
         )::integer
  FROM public.recycle_rate_for(p_product_type, p_prize_total) r;
$$;

COMMENT ON FUNCTION public.calc_recycle_value IS
  '回收價唯一規則來源，讀 recycle_rates。基準為單抽價。dismantle_prizes（實際入帳）與 estimate_recycle_value（前台預覽）都呼叫它。';

GRANT EXECUTE ON FUNCTION public.calc_recycle_value(text, numeric, integer) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.recycle_rate_for(text, integer) TO authenticated, service_role;

-- ── 前台預覽 RPC ───────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.estimate_recycle_value(p_record_ids bigint[])
RETURNS TABLE (
  draw_record_id bigint,
  recycle_value  integer,
  can_recycle    boolean,
  reason         text
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$
  SELECT
    dr.id,
    public.calc_recycle_value(p.type, p.price, pp.total),
    (dr.status = 'in_warehouse' AND p.sale_mode <> 'lottery'),
    CASE
      WHEN p.sale_mode = 'lottery'     THEN 'lottery'
      WHEN dr.status <> 'in_warehouse' THEN 'not_in_warehouse'
      ELSE NULL
    END
  FROM public.draw_records   dr
  JOIN public.product_prizes pp ON pp.id = dr.product_prize_id
  JOIN public.products       p  ON p.id  = pp.product_id
  WHERE dr.id = ANY(p_record_ids)
    AND dr.user_id = auth.uid();
$$;

REVOKE ALL ON FUNCTION public.estimate_recycle_value(bigint[]) FROM public;
GRANT EXECUTE ON FUNCTION public.estimate_recycle_value(bigint[]) TO authenticated;

-- ── 實際入帳 ───────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.dismantle_prizes(
  p_record_ids bigint[],
  p_user_id    uuid
) RETURNS TABLE (success_count integer, total_refund integer)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_record      RECORD;
  v_refund      INTEGER := 0;
  v_count       INTEGER := 0;
  v_prize_value INTEGER;
BEGIN
  FOR v_record IN
    SELECT dr.id, dr.product_prize_id, pp.total, p.price, p.type AS product_type
    FROM   public.draw_records   dr
    JOIN   public.product_prizes pp ON pp.id = dr.product_prize_id
    JOIN   public.products       p  ON p.id  = pp.product_id
    WHERE  dr.id      = ANY(p_record_ids)
      AND  dr.user_id = p_user_id
      AND  dr.status  = 'in_warehouse'
      -- 抽籤販售的中籤品項不可回收：那是 0 元抽來的，
      -- 回收等於沒付一毛錢就換到 G 幣
      AND  p.sale_mode <> 'lottery'
  LOOP
    v_prize_value := public.calc_recycle_value(
      v_record.product_type, v_record.price, v_record.total
    );

    UPDATE public.draw_records
    SET status = 'dismantled', refund_amount = v_prize_value
    WHERE id = v_record.id;

    -- 轉蛋/盒玩：回收後庫存歸還原商品（實體仍在廠商手上，可再次出貨）
    -- 一番賞/抽卡/自製賞為序列商品不加回，避免破壞抽獎順序與種子驗證
    IF v_record.product_type IN ('gacha', 'blindbox') AND v_record.product_prize_id IS NOT NULL THEN
      UPDATE public.product_prizes
      SET remaining = COALESCE(remaining, 0) + 1
      WHERE id = v_record.product_prize_id;
    END IF;

    INSERT INTO public.admin_recycle_pool (
      draw_record_id, user_id, product_id, product_prize_id, prize_name, prize_level, recycle_value
    )
    SELECT v_record.id, p_user_id, pp.product_id, pp.id, pp.name, pp.level, v_prize_value
    FROM   public.product_prizes pp
    WHERE  pp.id = v_record.product_prize_id
    ON CONFLICT DO NOTHING;

    v_refund := v_refund + v_prize_value;
    v_count  := v_count  + 1;
  END LOOP;

  IF v_refund > 0 THEN
    UPDATE public.users
    SET tokens = COALESCE(tokens, 0) + v_refund
    WHERE id = p_user_id;
  END IF;

  RETURN QUERY SELECT v_count, v_refund;
END;
$$;

