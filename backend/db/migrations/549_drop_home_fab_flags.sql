--
-- 2026-08-13 這顆按鈕的設定方式改過三輪，最後定案是**完全不需要自己的旗標**：
--
--   1. 一開始：後台「功能開關 → 類別」多一列 home_fab 手動顯示／隱藏（migration 548）
--   2. 中間：另開一個「首頁懸浮按鈕」頁籤，四個入口各給一個 home_fab_* 旗標
--   3. 定案：整顆按鈕的顯示與否**由那四個入口自己算出來** ——
