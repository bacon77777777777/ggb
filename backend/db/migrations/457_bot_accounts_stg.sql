INSERT INTO auth.users (id, instance_id, aud, role, email, encrypted_password,
                        email_confirmed_at, created_at, updated_at,
                        raw_app_meta_data, raw_user_meta_data)
SELECT gen_random_uuid(), '00000000-0000-0000-0000-000000000000',
       'authenticated', 'authenticated',
       'ggb_bot_' || lpad(n::text,3,'0') || '_' ||
         (extract(epoch from now())*1000)::bigint || '@ggb-internal.io',
       crypt(gen_random_uuid()::text, gen_salt('bf')), now(), now(), now(),
       '{"provider":"email","providers":["email"]}'::jsonb, '{}'::jsonb
FROM bot_names b
WHERE NOT EXISTS (
  SELECT 1 FROM public.users u
  WHERE u.email LIKE 'ggb_bot_' || lpad(b.n::text,3,'0') || '\_%@ggb-internal.io'
);

-- 補上機器人欄位。數值分布與 PROD 同一套公式，看起來才像同一批人
UPDATE public.users u
   SET is_bot      = true,
       name        = b.nm,
       avatar_url  = '/images/avatar/' || lpad((1 + (b.n % 8))::text, 2, '0') || '.png',
       tokens      = 4 + (b.n * 7) % 787,
       points      = 2 + (b.n * 29) % 2991,
       total_draws = 1 + (b.n * 13) % 874,
       created_at  = timestamptz '2025-08-30' + ((b.n * 3) % 308) * interval '1 day'
  FROM bot_names b
 WHERE u.email LIKE 'ggb_bot_' || lpad(b.n::text,3,'0') || '\_%@ggb-internal.io'
   AND NOT u.is_bot;

SELECT count(*) AS 機器人總數 FROM users WHERE is_bot;
