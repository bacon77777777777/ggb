-- 643：news 加「主題正規化鍵」，擋掉標題相似度與封面雜湊都攔不到的重複（2026-08-29）
--
-- 老闆 2026-08-29 回報近期文章有重複。實測那幾組的標題 Jaccard 相似度：
--   0.400  無職轉生III艾莉絲完成品公仔      ≈ 《無職轉生III》劍王艾莉絲…Lucrea
--   0.317  寶可夢卡牌30週年追加抽選         ≈ 寶可夢卡牌30週年 Yodobashi線上抽選
--   0.286  《阿卡納迪亞》惡魔型迪亞茲巴尼爾  ≈ 《亞爾卡那迪亞》惡魔型迪亞茲蕾菲爾卡
--   ────────────────────────────────────────────────
--   0.294  無職轉生III艾莉絲               ≈ 無職轉生III 羅琪西亞水著Ver.（不同商品，該留）
-- 門檻是 0.55 所以全漏。但**不能只把門檻調低**：最後那組是不同角色的不同商品，
-- 分數卻比真重複的 0.286 還高 —— 字元 bigram 這個指標根本分不開這兩件事。
--
-- 642 的 cover_hash 也攔不到這幾組：官方同一則發表會發多張不同角度的照片，
-- 兩篇各抓一張，雜湊當然不同。
--
-- 改用確定的訊號：改寫時讓 Claude 順手吐一個「作品／角色或型號／商品型態」的
-- 正規化鍵（同一次呼叫多要一個欄位，成本是零），拿它比對。
-- 「無職轉生/艾莉絲/景品公仔」與「無職轉生/羅琪西亞/景品公仔」是不同鍵、都留；
-- 兩篇艾莉絲則是同一個鍵、擋掉。不是猜相似度，是比對同一件商品。

ALTER TABLE public.news ADD COLUMN IF NOT EXISTS subject_key text;

COMMENT ON COLUMN public.news.subject_key IS
  '主題正規化鍵「作品/角色或型號/商品型態」，去標點小寫後儲存；news-agent 用它擋重複文章';

CREATE INDEX IF NOT EXISTS idx_news_subject_key
  ON public.news (subject_key) WHERE subject_key IS NOT NULL;
