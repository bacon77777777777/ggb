/** 把既有地址拆回（縣市, 區, 其餘）；拆不動就整串放 rest（相容自由填寫的舊資料） */
export function splitTwAddress(addr: string): { city: string; district: string; rest: string } {
  const a = (addr || '').trim().replace(/^臺/, '台');
  for (const city of TW_CITIES) {
    if (!a.startsWith(city)) continue;
    const tail = a.slice(city.length);
    for (const d of TW_DISTRICTS[city]) {
      if (tail.startsWith(d)) return { city, district: d, rest: tail.slice(d.length).trim() };
    }
    return { city, district: '', rest: tail.trim() };
  }
  return { city: '', district: '', rest: a };
}
