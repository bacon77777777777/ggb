/**
 * 首頁懸浮選單的扇形排列（純幾何，沒有 React）
 *
 * 抽成獨立檔案是為了**能被驗證腳本直接 import**。
 * 之前把公式寫在元件裡、驗證腳本自己再算一次，結果腳本用了相反的座標慣例，
 * 把「整排往下噴」的 bug 抵銷掉、量出來看起來完全正常（2026-08-13）。
 * 同一份程式碼被兩邊共用，就不會再有那種事。
 *
 * ── 排法 ──
 * 角度在 180°（正左）～270°（正上）之間依數量均分。
 * 內圈固定三個槽（正左／斜上／正上），第四、五顆補在外圈的空隙。
 * 內圈三顆彼此 45°、半徑 84px 時剛好 64px 貼著過；外圈那兩顆插在中間，
 * 與內圈鄰居相距 68px，都不會疊到。
 *
 * 上限 5 顆。再多就該換版型（改直排），不是把半徑繼續撐大 —— 那會頂到畫面左緣。
 */

/*
 * 半徑。這兩個數字是算出來的，不是喬出來的：
 *
 *   同一圈上相鄰兩顆的距離 = 2R·sin(半角)
 *   3 顆同圈（45° 間隔）要不重疊 → 2R·sin(22.5°) ≥ 64 → R ≥ 83.6
 *
 * 內圈取 84（貼著下限，老闆要求盡量靠攏），外圈按同比例取 138，
 * 交錯時相鄰仍有 77px。改子鈕尺寸時這兩個數字要一起重算，
 * 用 `.tmp/fancheck` 那支跑一遍 1～5 顆就知道有沒有疊到。
 */
/** 內圈半徑（px） */
export const RADIUS_INNER = 84;
/** 外圈半徑（px）：4 顆以上交錯時用 */
export const RADIUS_OUTER = 138;
/** 最多幾顆 */
export const FAN_MAX = 5;

/**
 * 固定版位。
 *
 * ⚠️ **角度不隨顆數改變**（老闆指定）。原本是把 180°～270° 依顆數均分，
 * 結果開第四個入口時前三顆會整排位移 —— 玩家記住的位置一夕之間全變了。
 *
 * 改成固定槽位：前三顆永遠是正左／斜上／正上，第四、五顆補在外圈的空隙。
 * 這樣開關某一個入口只會讓那一顆出現或消失，其他不動。
 */
const INNER_SLOTS = [180, 225, 270]      // 內圈：正左 → 斜上 → 正上
const OUTER_SLOTS = [202.5, 247.5]       // 外圈：補在內圈兩兩之間

/**
 * 第 index 顆相對主鈕中心的位移。
 *
 * 回傳的是**CSS 座標**（+y 朝下），可以直接餵給 framer-motion 的 x / y。
 * ⚠️ 不要再對 y 取負號：數學角度是 +y 朝上，而 `sin(225°)`、`sin(270°)`
 * 本來就是負的，也就是算出來的 y 已經是「CSS 的往上」。多翻一次就會整排往下噴。
 */
export function fanOffset(index: number): { x: number; y: number } {
  const inner = index < INNER_SLOTS.length
  const deg = inner ? INNER_SLOTS[index] : OUTER_SLOTS[index - INNER_SLOTS.length]
  const r = inner ? RADIUS_INNER : RADIUS_OUTER
  const rad = (deg * Math.PI) / 180
  return { x: Math.cos(rad) * r, y: Math.sin(rad) * r }
}
